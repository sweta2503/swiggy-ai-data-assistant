-- Gold: the star schema. Facts (events) surrounded by dimensions (who/what/where/when).
-- Safe to re-run: everything is IF NOT EXISTS.
--
-- Conventions
--   * Surrogate keys (xxx_sk) are meaningless integers. -1 is the "Unknown" member: a fact that
--     cannot find its dimension row points there instead of being dropped.
--   * Validity windows are half-open: valid_from <= date < valid_to. Current rows use 9999-12-31.
--   * No PII lives in the dimensions. Customer contact details are in gold.customer_pii.

CREATE TABLE IF NOT EXISTS gold.festival_calendar (
    festival_date date PRIMARY KEY,
    festival_name text NOT NULL
);

-- ---------------------------------------------------------------- dimensions ---------------
CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key         integer PRIMARY KEY,          -- 20260301
    full_date        date    NOT NULL UNIQUE,      -- an IST calendar date
    day_name         text    NOT NULL,
    day_of_week      smallint NOT NULL,            -- 1 = Monday .. 7 = Sunday
    is_weekend       boolean NOT NULL,
    week_start_date  date    NOT NULL,             -- the Monday of that week
    month_start_date date    NOT NULL,
    month_name       text    NOT NULL,
    quarter          smallint NOT NULL,
    year             smallint NOT NULL,
    is_festival      boolean NOT NULL DEFAULT false,
    festival_name    text
);

CREATE TABLE IF NOT EXISTS gold.dim_city (
    city_sk   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.dim_restaurant (
    restaurant_sk  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  text NOT NULL UNIQUE,
    name           text NOT NULL,
    cuisine        text NOT NULL,
    city_sk        integer NOT NULL REFERENCES gold.dim_city (city_sk),
    rating         numeric(3,1),
    onboarded_date date,
    is_active      boolean
);

-- Delivery partners: only business attributes. Name and phone are personal data and are not
-- needed for any analytics question, so they stay out of gold.
CREATE TABLE IF NOT EXISTS gold.dim_partner (
    partner_sk  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id  text NOT NULL UNIQUE,
    city_sk     integer NOT NULL REFERENCES gold.dim_city (city_sk),
    joined_date date
);

-- SCD Type 2: one row per customer per period in which (city, segment) stayed the same.
CREATE TABLE IF NOT EXISTS gold.dim_customer (
    customer_sk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id text    NOT NULL,
    city_sk     integer NOT NULL REFERENCES gold.dim_city (city_sk),
    city        text    NOT NULL,
    segment     text    NOT NULL,
    valid_from  date    NOT NULL,
    valid_to    date    NOT NULL,
    is_current  boolean NOT NULL,
    UNIQUE (customer_id, valid_from),
    CHECK (valid_from < valid_to)
);
-- exactly one current row per customer, enforced by the database
CREATE UNIQUE INDEX IF NOT EXISTS dim_customer_one_current
    ON gold.dim_customer (customer_id) WHERE is_current;

-- Restricted: the only place customer contact details exist in gold. Never exposed to the
-- assistant (phase 7 grants nothing on this table).
CREATE TABLE IF NOT EXISTS gold.customer_pii (
    customer_id  text PRIMARY KEY,
    name         text,
    phone        text,
    email        text,
    address_line text,
    pincode      text,
    updated_at   timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- facts --------------------
-- GRAIN: one row per order.
-- Range-partitioned by month on order_date_ist: a query for one month reads one partition.
-- Postgres requires the partition key inside any unique key, so the key is (order_id,
-- order_date_ist). order_id on its own is still unique (checked by tests and data quality).
CREATE TABLE IF NOT EXISTS gold.fact_orders (
    order_id            text    NOT NULL,
    order_date_ist      date    NOT NULL REFERENCES gold.dim_date (full_date),
    order_ts_utc        timestamptz NOT NULL,
    order_ts_ist        timestamp   NOT NULL,
    customer_sk         integer NOT NULL REFERENCES gold.dim_customer (customer_sk),
    restaurant_sk       integer NOT NULL REFERENCES gold.dim_restaurant (restaurant_sk),
    partner_sk          integer NOT NULL REFERENCES gold.dim_partner (partner_sk),
    city_sk             integer NOT NULL REFERENCES gold.dim_city (city_sk),
    status              text    NOT NULL,
    platform            text,
    delivery_minutes    integer,
    order_value         numeric(12,2) NOT NULL,   -- items total, before discount
    discount            numeric(12,2) NOT NULL,
    delivery_fee        numeric(12,2) NOT NULL,
    taxes               numeric(12,2) NOT NULL,
    -- the business definition, computed once: delivered orders only, items minus discount,
    -- excluding delivery fee and taxes
    net_revenue         numeric(12,2) NOT NULL,
    _silver_ingested_at timestamptz NOT NULL,     -- lets the loader spot changed silver rows
    PRIMARY KEY (order_id, order_date_ist)
) PARTITION BY RANGE (order_date_ist);

-- Strays outside the created months land here instead of failing the load.
CREATE TABLE IF NOT EXISTS gold.fact_orders_default PARTITION OF gold.fact_orders DEFAULT;

CREATE OR REPLACE FUNCTION gold.ensure_order_partitions(first_day date, last_day date)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    m date := date_trunc('month', first_day)::date;
BEGIN
    IF first_day IS NULL OR last_day IS NULL THEN RETURN; END IF;
    WHILE m <= last_day LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS gold.%I PARTITION OF gold.fact_orders'
            ' FOR VALUES FROM (%L) TO (%L)',
            'fact_orders_' || to_char(m, 'YYYY_MM'), m, (m + interval '1 month')::date);
        m := (m + interval '1 month')::date;
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS fact_orders_customer_idx   ON gold.fact_orders (customer_sk);
CREATE INDEX IF NOT EXISTS fact_orders_restaurant_idx ON gold.fact_orders (restaurant_sk);
CREATE INDEX IF NOT EXISTS fact_orders_city_date_idx  ON gold.fact_orders (city_sk, order_date_ist);

-- GRAIN: one row per item line on an order.
-- Never add order_value from fact_orders to a sum over this table: it repeats per line.
CREATE TABLE IF NOT EXISTS gold.fact_order_items (
    order_item_id       text PRIMARY KEY,
    order_id            text    NOT NULL,
    order_date_ist      date    NOT NULL,
    restaurant_sk       integer NOT NULL REFERENCES gold.dim_restaurant (restaurant_sk),
    item_id             text,
    item_name           text,
    item_category       text,
    qty                 integer NOT NULL,
    unit_price          numeric(10,2) NOT NULL,
    line_total          numeric(12,2) NOT NULL,
    _silver_ingested_at timestamptz NOT NULL,
    FOREIGN KEY (order_id, order_date_ist) REFERENCES gold.fact_orders (order_id, order_date_ist)
);
CREATE INDEX IF NOT EXISTS fact_items_order_idx ON gold.fact_order_items (order_id);
CREATE INDEX IF NOT EXISTS fact_items_rest_idx  ON gold.fact_order_items (restaurant_sk);

-- GRAIN: one row per refund.
CREATE TABLE IF NOT EXISTS gold.fact_refunds (
    refund_id           text PRIMARY KEY,
    order_id            text    NOT NULL,
    order_date_ist      date    NOT NULL,
    refund_date_ist     date    NOT NULL REFERENCES gold.dim_date (full_date),
    refund_ts_ist       timestamp NOT NULL,
    customer_sk         integer NOT NULL REFERENCES gold.dim_customer (customer_sk),
    restaurant_sk       integer NOT NULL REFERENCES gold.dim_restaurant (restaurant_sk),
    city_sk             integer NOT NULL REFERENCES gold.dim_city (city_sk),
    refund_amount       numeric(12,2) NOT NULL,
    reason_code         text,
    _silver_ingested_at timestamptz NOT NULL,
    FOREIGN KEY (order_id, order_date_ist) REFERENCES gold.fact_orders (order_id, order_date_ist)
);
CREATE INDEX IF NOT EXISTS fact_refunds_order_idx ON gold.fact_refunds (order_id);
CREATE INDEX IF NOT EXISTS fact_refunds_city_idx  ON gold.fact_refunds (city_sk, refund_date_ist);
CREATE INDEX IF NOT EXISTS fact_refunds_rest_idx  ON gold.fact_refunds (restaurant_sk);

-- ---------------------------------------------------------------- aggregate ----------------
-- GRAIN: one row per IST day per city. Rebuilt from fact_orders on every run, so it can never
-- drift from the facts. A fast path for the most common questions.
CREATE TABLE IF NOT EXISTS gold.daily_city_sales (
    order_date_ist       date    NOT NULL REFERENCES gold.dim_date (full_date),
    city_sk              integer NOT NULL REFERENCES gold.dim_city (city_sk),
    orders               integer NOT NULL,   -- every order placed
    delivered_orders     integer NOT NULL,
    cancelled_orders     integer NOT NULL,
    refunded_orders      integer NOT NULL,
    failed_orders        integer NOT NULL,
    gross_order_value    numeric(14,2) NOT NULL,  -- delivered orders: items before discount
    discount_total       numeric(14,2) NOT NULL,  -- delivered orders
    net_revenue          numeric(14,2) NOT NULL,  -- gross_order_value - discount_total
    avg_delivery_minutes numeric(6,2),            -- delivered orders
    PRIMARY KEY (order_date_ist, city_sk)
);
